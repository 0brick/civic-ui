// Writes docs/component-index.md: every component and section with its file,
// props, emits, slots, dependencies and dependents.
//   npm run docs:index            regenerate
//   npm run docs:index -- --check fail if the file is out of date (CI)
// Regex-based: relies on the one-prop-per-line defineProps({...}) style.
import { existsSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative, basename, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'docs', 'component-index.md')
const src = join(root, 'src')

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name)
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.vue') ? [p] : []
  })
}

const files = ['components', 'sections', 'layout'].flatMap((d) => walk(join(src, d))).sort()
const exported = new Set([...readFileSync(join(src, 'index.js'), 'utf8').matchAll(/^import (\w+) from '\.\/(?:components|sections|layout)\//gm)].map((m) => m[1]))

function blockAfter(code, marker) {
  const start = code.indexOf(marker)
  if (start === -1) return ''
  let i = code.indexOf('{', start)
  if (i === -1) return ''
  let depth = 0
  for (let j = i; j < code.length; j++) {
    if (code[j] === '{') depth++
    else if (code[j] === '}' && --depth === 0) return code.slice(i + 1, j)
  }
  return ''
}

function parseProps(script) {
  const body = blockAfter(script, 'defineProps(')
  const props = []
  let depth = 0
  let current = ''
  for (const line of body.split('\n')) {
    const trimmed = line.trim()
    if (depth === 0) {
      const m = trimmed.match(/^(\w+):\s*(.*)$/)
      if (!m) continue
      const comment = (m[2].match(/\/\/\s*(.*)$/) || [])[1] || ''
      current = { name: m[1], raw: m[2].replace(/\/\/.*$/, ''), comment }
      props.push(current)
    } else if (current) {
      current.raw += ' ' + trimmed.replace(/\/\/.*$/, '')
    }
    for (const ch of line.replace(/\/\/.*$/, '')) {
      if (ch === '{' || ch === '(' || ch === '[') depth++
      else if (ch === '}' || ch === ')' || ch === ']') depth--
    }
  }
  return props.map(({ name, raw, comment }) => {
    const type = (raw.match(/type:\s*(\[[^\]]+\]|\w+)/) || [])[1] || (/^\w+,?$/.test(raw) ? raw.replace(',', '') : '?')
    const def = (raw.match(/default:\s*(\(\) => \[\]|\(\) => \(\{\}\)|'[^']*'|"[^"]*"|[\w.-]+)/) || [])[1]
    const values = (raw.match(/\[([^\]]+)\]\.includes\(v\)/) || [])[1]
    const required = /required:\s*true/.test(raw)
    let line = `\`${name}\`: ${type.replace(/[[\]]/g, '').replace(/,\s*/g, '|')}`
    if (values) line += ` (${values.replace(/'/g, '').replace(/,\s*/g, '|')})`
    if (required) line += ' **required**'
    else if (def !== undefined) line += ` = ${def.replace('() => []', '[]').replace('() => ({})', '{}')}`
    if (comment) line += `: ${comment}`
    return line
  })
}

const info = files.map((file) => {
  const code = readFileSync(file, 'utf8')
  const script = (code.match(/<script setup>([\s\S]*?)<\/script>/) || [])[1] || ''
  const template = (code.match(/<template>([\s\S]*)<\/template>/) || [])[1] || ''
  const name = basename(file, '.vue')
  const imports = [...script.matchAll(/^import (\w+) from '([^']+)'/gm)].filter((m) => m[2].endsWith('.vue')).map((m) => m[1])
  const helpers = [...script.matchAll(/^import \{([^}]+)\} from '[^']*\/(composables|utils)\/(\w+)'/gm)].map((m) => `${m[3]}(${m[1].trim().replace(/\s+/g, ' ')})`)
  const emits = (script.match(/defineEmits\(\[([^\]]*)\]\)/) || [])[1]
  const slots = [...new Set([...template.matchAll(/<slot(?:\s+name="([\w-]+)")?/g)].map((m) => m[1] || 'default'))]
  const header = (script.match(/^\s*((?:\/\/.*\n)+)/) || [])[1]
  // the header comment's first sentence
  const text = header ? header.split('\n').map((l) => l.replace(/^\s*\/\/\s?/, '')).join(' ').replace(/\s+/g, ' ').trim() : ''
  const sentence = (text.match(/^.*?[.:](?=\s|$)/) || [text])[0]
  const summary = sentence.length > 220 ? sentence.slice(0, 217) + '…' : sentence
  return {
    name,
    file: relative(root, file),
    group: relative(src, dirname(file)),
    exported: exported.has(name),
    imports,
    helpers,
    emits: emits ? emits.replace(/'/g, '').split(',').map((s) => s.trim()).filter(Boolean) : [],
    slots,
    props: parseProps(script),
    summary
  }
})

const usedBy = {}
for (const c of info) for (const dep of c.imports) (usedBy[dep] ||= []).push(c.name)

let md = `# Component index

Generated by \`npm run docs:index\`. Do not edit by hand.
Per component: file, summary, props (\`name\`: type (allowed values) = default), emits, slots,
**builds on** (child components), **helpers** (composables and utils), **used by** (dependents).
_internal_ = not exported from src/index.js.
`
let group = ''
for (const c of info) {
  if (c.group !== group) {
    group = c.group
    md += `\n## ${group}\n`
  }
  md += `\n### ${c.name}${c.exported ? '' : ' _(internal)_'}\n\n\`${c.file}\`${c.summary ? `: ${c.summary}` : ''}\n\n`
  if (c.props.length) md += `- props: ${c.props.join('; ')}\n`
  if (c.emits.length) md += `- emits: ${c.emits.join(', ')}\n`
  if (c.slots.length) md += `- slots: ${c.slots.join(', ')}\n`
  if (c.imports.length) md += `- builds on: ${c.imports.join(', ')}\n`
  if (c.helpers.length) md += `- helpers: ${c.helpers.join('; ')}\n`
  if (usedBy[c.name]) md += `- used by: ${usedBy[c.name].join(', ')}\n`
}

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current !== md) {
    console.error('docs/component-index.md is out of date. Run: npm run docs:index')
    process.exit(1)
  }
} else {
  writeFileSync(out, md)
  console.log(`docs/component-index.md: ${info.length} components`)
}
